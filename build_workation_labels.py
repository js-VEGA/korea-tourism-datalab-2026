NON89_CONTEXT = ["강릉시", "속초시", "춘천시", "동해시", "제주시", "여수시", "거제시",
                 "제천시", "순천시", "나주시", "포항시", "경주시", "군산시", "통영시"]


def main():
    reg89 = set()
    with open(os.path.join(BASE, "regions.csv"), encoding="utf-8-sig") as f:
        for r in csv.DictReader(f):
            reg89.add(r["지역명"].strip())

    rows = []
    for full, yr, conf, note in CURATED:
        rows.append({
            "지역명_full": full,
            "in89": full in reg89,
            "추정_시작연도": yr,
            "확실도": conf,
            "근거": note,
        })
    miss = [r for r in rows if not r["in89"]]
    if miss:
        print("regions.csv 표기 불일치:", [r["지역명_full"] for r in miss])

    path = os.path.join(OUT, "workation_designated_regions.csv")
    with open(path, "w", newline="", encoding="utf-8-sig") as f:
        w = csv.DictWriter(f, fieldnames=["지역명_full", "in89", "추정_시작연도", "확실도", "근거"])
        w.writeheader(); w.writerows(rows)

    n89 = sum(1 for r in rows if r["in89"])
    hi = sum(1 for r in rows if r["확실도"] == "높음")
    print(f"큐레이션 워케이션 지역: {len(rows)}건 (89개 중 {n89}개, 확실도 '높음' {hi}개)")
    print(f"→ {path}")
    print(f"참고(89 밖 운영지): {', '.join(NON89_CONTEXT)}")


if __name__ == "__main__":
    main()
